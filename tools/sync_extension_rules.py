"""Generate the browser-side copies of the shared URL rules.

Single source of truth:
    sentinel/data/url_rules.json   brand / domain / TLD / keyword lists and the double-extension pattern
    sentinel/config.py             SUSPICIOUS_THRESHOLD / MALICIOUS_THRESHOLD

Generated (never edit by hand):
    browser_extension/url_rules.js   loaded by the extension before analyzer.js
    docs/url_rules.js                same file for the website
    docs/analyzer.js                 byte-for-byte copy of browser_extension/analyzer.js

Run:  python tools/sync_extension_rules.py          write the files
      python tools/sync_extension_rules.py --check  exit 1 if any file is out of date (used by the tests)
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from sentinel import config  # noqa: E402

HEADER = ("// GENERATED by tools/sync_extension_rules.py from sentinel/data/url_rules.json and sentinel/config.py.\n"
          "// Do not edit by hand: change the JSON/config, then run the script.\n")


def render_rules_js() -> str:
    rules = json.loads(config.URL_RULES_FILE.read_text(encoding="utf-8"))
    rules.pop("_comment", None)
    rules["suspicious_at"] = config.SUSPICIOUS_THRESHOLD
    rules["malicious_at"] = config.MALICIOUS_THRESHOLD
    return HEADER + "const URL_RULES = " + json.dumps(rules, indent=2) + ";\n"


def expected_files() -> dict:
    """{path: bytes} for every generated file."""
    rules_js = render_rules_js().encode("utf-8")
    analyzer = (ROOT / "browser_extension" / "analyzer.js").read_bytes()
    return {
        ROOT / "browser_extension" / "url_rules.js": rules_js,
        ROOT / "docs" / "url_rules.js": rules_js,
        ROOT / "docs" / "analyzer.js": analyzer,
    }


def out_of_date() -> list:
    return [p for p, data in expected_files().items() if not p.exists() or p.read_bytes() != data]


def main(argv=None) -> int:
    check = "--check" in (argv if argv is not None else sys.argv[1:])
    stale = out_of_date()
    if check:
        for p in stale:
            print(f"out of date: {p.relative_to(ROOT)}", file=sys.stderr)
        return 1 if stale else 0
    for p, data in expected_files().items():
        p.write_bytes(data)
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
